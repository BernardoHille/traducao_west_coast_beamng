def op_panel(el, color, opacity, rng, cover_log):
    """Painted legend on an opaque panel: remove old legend, draw the new one (mask untouched)."""
    rgb = color[..., :3]
    legend = LEGEND[el["legend"]](rgb.astype(int))
    hole = np.zeros(legend.shape, bool)
    for b in el.get("erase", []):
        sy, sx = box_slices(b)
        pix = rgb[sy, sx].astype(np.float64)
        strict = legend[sy, sx]
        near = dilate(strict, 2)
        lref = np.median(pix[strict], 0)
        bref = np.median(pix[~near], 0) if (~near).any() else 255 - lref
        dl = np.linalg.norm(pix - lref, axis=-1)
        db = np.linalg.norm(pix - bref, axis=-1)
        # anything that is not clean background near the legend is legend (incl. faint anti-aliasing)
        hole[sy, sx] |= ((dl < db * 1.25) | (db > el.get("bg_tol", 18))) & dilate(strict, 3)
    keep = np.zeros_like(hole)
    for b in el.get("keep", []):
        sy, sx = box_slices(b)
        keep[sy, sx] = True
    ebox = np.zeros_like(hole)
    for b in el.get("erase", []):
        ebox[box_slices(b)] = True
    hole = dilate(hole, el.get("erase_dilate", 1)) & ~keep & ebox
    ex = el["box"]
    sy, sx = box_slices(ex)
    hole_c = hole[sy, sx]
    flat = np.zeros_like(hole)
    for b in el.get("fill_boxes", []):  # areas repainted entirely (e.g. a coloured block removed)
        by, bx = box_slices(b)
        flat[by, bx] = True
    hole &= ~flat
    hole_c = hole[sy, sx]
    legend_sel = legend & ~dilate(~legend, 1)
    src_legend = rgb.copy()
    crop = rgb[sy, sx].copy()
    if hole_c.any():
        fill_src = crop.copy()
        if "bg_from" in el:  # sample background grain from a clean area
            by, bx = box_slices(el["bg_from"])
            bgpix = rgb[by, bx].reshape(-1, 3).astype(np.float64)
            fill = np.median(bgpix, 0)
            known = ~hole_c
            fill_src[hole_c] = fill
        new = inpaint(fill_src, hole_c, rng, iters=el.get("inpaint_iters", 300))
        crop = new.astype(np.uint8)
    flat_c = flat[sy, sx]
    if flat_c.any():
        by, bx = box_slices(el["bg_from"])
        bg = np.zeros(legend.shape, bool)
        bg[by, bx] = True
        crop[flat_c] = grain_color(rgb, bg, rng, flat_c.sum()).clip(0, 255).astype(np.uint8)
    # draw lines
    lsel = legend_sel.copy()
    if "legend_from" in el:
        by, bx = box_slices(el["legend_from"])
        m = np.zeros_like(lsel)
        m[by, bx] = lsel[by, bx]
        lsel = m
    else:
        m = np.zeros_like(lsel)
        for b in el.get("erase", []):
            by, bx = box_slices(b)
            m[by, bx] |= lsel[by, bx]
        lsel = m
    cov = np.zeros(legend.shape)
    for line in el.get("lines", []):
        spec = dict(el.get("style", {}))
        spec.update(line.get("style", {}))
        cov = np.maximum(cov, render_line(line["text"], spec, line["box"], spec.get("cap_ref", "H")))
    cov_c = cov[sy, sx]
    ink = cov_c > 0.02
    if ink.any():
        if "color" in el:
            lc = np.tile(np.array(el["color"], np.float64), (ink.sum(), 1))
        else:
            lc = grain_color(src_legend, lsel, rng, ink.sum())
        a = cov_c[ink][:, None]
        c = crop[ink].astype(np.float64)
        crop[ink] = (c * (1 - a) + lc * a).clip(0, 255).astype(np.uint8)
    color[sy, sx, :3] = crop
    cover_log.append(el["id"])


def op_glyph(el, color, opacity, rng, cover_log):
    """Glyph tile: the letter shape lives in the opacity map; rewrite mask + base colour of the tile."""
    sy, sx = box_slices(el["box"])
    old = opacity[sy, sx, 0] > 128
    rgb = color[..., :3]
    letter_sel = np.zeros(opacity.shape[:2], bool)
    letter_sel[sy, sx] = old
    cov = np.zeros(opacity.shape[:2])
    for line in el["lines"]:
        if line.get("box") == "auto" or "box" not in line:
            line["box"] = auto_line_box(old, el["box"], el.get("safe", el["box"]))
        spec = dict(el.get("style", {}))
        spec.update(line.get("style", {}))
        cov = np.maximum(cov, render_line(line["text"], spec, line["box"], spec.get("cap_ref", "H")))
    cov_c = cov[sy, sx]
    # opacity: clear the tile, write new letters (RGB channels, alpha untouched)
    newmask = (cov_c * 255).round().astype(np.uint8)
    for ch in range(3):
        opacity[sy, sx, ch] = newmask
    # base colour: letters painted with the original letter colour (+grain), bled 3 px so that
    # bilinear/mip filtering at the mask edge never picks the old background
    ink = dilate(cov_c > 0.02, 3)
    lc = grain_color(rgb, letter_sel, rng, ink.sum())
    crop = color[sy, sx, :3].copy()
    crop[ink] = lc.clip(0, 255).astype(np.uint8)
    color[sy, sx, :3] = crop
    cover_log.append(el["id"])


def op_r2(el, color, opacity, rng, cover_log):
    """US YIELD -> Brazilian R-2: white field, red border (orla), no legend. Outer triangle untouched."""
    x0, y0, x1, y1 = el["box"]
    rgb = color[..., :3].astype(int)
    red = LEGEND["red"](rgb)
    sub = connected(red[y0:y1, x0:x1], el["seed"][1] - y0, el["seed"][0] - x0)
    ys, xs = np.nonzero(sub)
    # robust outer triangle: fit the slanted edges on the straight part of each side, top edge by median
    rows = range(ys.min() + 14, ys.max() - 30)
    yl, xl, xr = [], [], []
    for yy in rows:
        r = np.nonzero(sub[yy])[0]
        if len(r):
            yl.append(yy); xl.append(r.min()); xr.append(r.max() + 1)
    al, bl = np.polyfit(yl, xl, 1)
    ar, br = np.polyfit(yl, xr, 1)
    mid = range(int(al * (ys.min() + 14) + bl) + 20, int(ar * (ys.min() + 14) + br) - 20)
    ytop = float(np.median([np.nonzero(sub[:, c])[0].min() for c in mid]))
    ybot = (br - bl) / (al - ar)
    tri = np.array([[al * ytop + bl, ytop], [ar * ytop + br, ytop], [al * ybot + bl, ybot]]) + [x0, y0]
    cen = tri.mean(0)
    border = el["orla_px"]
    # inner triangle: offset each edge inward by `border`
    def inset(p, q, r_, d):
        # line through p,q moved towards r_
        n = np.array([-(q - p)[1], (q - p)[0]], float)
        n /= np.linalg.norm(n)
        if np.dot(r_ - p, n) < 0:
            n = -n
        return p + n * d, q + n * d

    lines = [inset(tri[0], tri[1], tri[2], border), inset(tri[1], tri[2], tri[0], border), inset(tri[2], tri[0], tri[1], border)]

    def intersect(l1, l2):
        (p1, p2), (p3, p4) = l1, l2
        d1, d2 = p2 - p1, p4 - p3
        cr = lambda u, v: u[0] * v[1] - u[1] * v[0]
        t = cr(p3 - p1, d2) / cr(d1, d2)
        return p1 + t * d1

    inner = np.array([intersect(lines[2], lines[0]), intersect(lines[0], lines[1]), intersect(lines[1], lines[2])])
    # coverage of the inner triangle (supersampled) inside box
    W, H = (x1 - x0) * SS, (y1 - y0) * SS
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).polygon([tuple((p - [x0, y0]) * SS) for p in inner], fill=255)
    cov = np.asarray(im.resize((x1 - x0, y1 - y0), Image.LANCZOS), np.float64) / 255.0
    # white field colour + grain from the existing white centre
    white = LEGEND["white"](rgb[y0:y1, x0:x1]) & (cov > 0.99)
    ink = cov > 0.01
    crop = color[y0:y1, x0:x1, :3].copy()
    wc = grain_color(color[y0:y1, x0:x1, :3], white, rng, ink.sum())
    a = cov[ink][:, None]
    crop[ink] = (crop[ink] * (1 - a) + wc * a).clip(0, 255).astype(np.uint8)
    color[y0:y1, x0:x1, :3] = crop
    el["_geometry"] = {"outer": tri.round(1).tolist(), "inner": inner.round(1).tolist()}
    cover_log.append(el["id"])


def op_r3(el, color, opacity, rng, cover_log):
    """DO NOT ENTER -> R-3: remove the white words, keep red disc, white bar and white rim."""
    rgb = color[..., :3]
    x0, y0, x1, y1 = el["box"]
    red = LEGEND["red"](rgb.astype(int))
    white = LEGEND["white"](rgb.astype(int))
    ys, xs = np.nonzero(red[y0:y1, x0:x1])
    cx, cy = x0 + (xs.min() + xs.max() + 1) / 2, y0 + (ys.min() + ys.max() + 1) / 2
    r_in = (xs.max() - xs.min() + 1) / 2 - el.get("rim_margin", 1)
    # white bar: white run through the centre
    icx, icy = int(round(cx)), int(round(cy))
    l = icx
    while white[icy, l - 1]:
        l -= 1
    r = icx
    while white[icy, r + 1]:
        r += 1
    t = icy
    while white[t - 1, icx]:
        t -= 1
    b = icy
    while white[b + 1, icx]:
        b += 1
    bx0, by0, bx1, by1 = l, t, r + 1, b + 1
    el["_geometry"] = {"center": [round(cx, 1), round(cy, 1)], "inner_radius": round(float(r_in), 1),
                       "bar": [int(bx0), int(by0), int(bx1), int(by1)]}
    yy, xx = np.mgrid[0:1024, 0:2048]
    disc = (xx - cx) ** 2 + (yy - cy) ** 2 <= r_in ** 2
    bar = (xx >= bx0) & (xx < bx1) & (yy >= by0) & (yy < by1)
    pix = rgb.astype(np.float64)
    wref = np.median(pix[white & disc & ~bar], 0)
    rref = np.median(pix[red & disc], 0)
    whitish = np.linalg.norm(pix - wref, axis=-1) < np.linalg.norm(pix - rref, axis=-1) * 1.4
    hole = dilate(whitish & disc & ~dilate(bar, 1), 1) & disc & ~dilate(bar, 1)
    crop = rgb[y0:y1, x0:x1].copy()
    h = hole[y0:y1, x0:x1]
    color[y0:y1, x0:x1, :3] = inpaint(crop, h, rng, iters=300).astype(np.uint8)
    cover_log.append(el["id"])


