# ---------------------------------------------------------------- inputs
def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def manifest_sha(name: str) -> str:
    import csv
    with open(REPO / "docs/inventory/original_files_manifest.csv", encoding="utf8") as f:
        for row in csv.DictReader(f):
            if row["filename"] == name and row["classification"].startswith("original"):
                return row["sha256"]
    raise SystemExit(f"{name} not in manifest")


def load_originals():
    for p in (ORIG_COLOR, ORIG_OPACITY):
        if not p.exists():
            raise SystemExit(f"missing original {p} (see docs/inventory/original_files_manifest.csv)")
        if sha256(p) != manifest_sha(p.name):
            raise SystemExit(f"SHA-256 mismatch for {p.name}: stop and investigate")
    color = np.array(Image.open(ORIG_COLOR).convert("RGBA"))
    opacity = np.array(Image.open(ORIG_OPACITY).convert("RGBA"))
    assert color.shape == (1024, 2048, 4) and opacity.shape == (1024, 2048, 4)
    return color, opacity


# ---------------------------------------------------------------- helpers
def box_slices(b):
    x0, y0, x1, y1 = b
    return slice(y0, y1), slice(x0, x1)


def dilate(m: np.ndarray, r: int) -> np.ndarray:
    out = m.copy()
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if dy * dy + dx * dx <= r * r:
                out |= np.roll(np.roll(m, dy, 0), dx, 1)
    return out


def box_blur(img: np.ndarray, r: int) -> np.ndarray:
    k = 2 * r + 1
    pad = np.pad(img, ((r, r), (r, r)) + ((0, 0),) * (img.ndim - 2), mode="edge").astype(np.float64)
    c = pad.cumsum(0).cumsum(1)
    c = np.pad(c, ((1, 0), (1, 0)) + ((0, 0),) * (img.ndim - 2))
    s = c[k:, k:] - c[:-k, k:] - c[k:, :-k] + c[:-k, :-k]
    return s / (k * k)


def inpaint(rgb: np.ndarray, hole: np.ndarray, rng: np.random.Generator, iters: int = 400) -> np.ndarray:
    """Diffusion fill of `hole` from the surrounding pixels, then re-grain with residuals of known pixels."""
    out = rgb.astype(np.float64).copy()
    known = ~hole
    if not known.any():
        return rgb
    out[hole] = out[known].mean(0)
    for _ in range(iters):
        acc = np.zeros_like(out)
        for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            acc += np.roll(np.roll(out, dy, 0), dx, 1)
        out[hole] = (acc / 4.0)[hole]
    base = rgb.astype(np.float64)
    clean = known & ~dilate(hole, 3)
    resid = (base - box_blur(base, 2))[clean]
    if len(resid):
        resid = np.clip(resid, -10, 10) * 0.8
        pick = rng.integers(0, len(resid), hole.sum())
        out[hole] += resid[pick]
    return out.clip(0, 255)


def grain_color(src: np.ndarray, sel: np.ndarray, rng, n: int) -> np.ndarray:
    """n colours = median legend colour + residual grain sampled from `sel` pixels of src."""
    pix = src[sel].astype(np.float64)
    med = np.median(pix, 0)
    if len(pix) < 4:
        return np.tile(med, (n, 1))
    resid = pix - pix.mean(0)
    resid = np.clip(resid, -25, 25) * 0.6
    return med + resid[rng.integers(0, len(pix), n)]


def font(spec: dict, size: int) -> ImageFont.FreeTypeFont:
    f = ImageFont.truetype(FONTS[spec.get("font", "bahnschrift")], size)
    try:
        f.set_variation_by_axes([spec.get("wght", 600), spec.get("wdth", 100)])
    except OSError:
        pass
    return f


def render_line(text: str, spec: dict, box, cap_ref="H") -> np.ndarray:
    """Coverage of `text`: capital height == box height; narrows the font width axis (down to
    `min_wdth`) before squeezing horizontally, so long PT-BR words keep real letter shapes."""
    spec = dict(spec)
    wd = spec.get("wdth", 100)
    while True:
        cov, ink_w = _render_line(text, spec, box, cap_ref)
        if ink_w <= (box[2] - box[0]) * spec.get("max_width", 1.0) or spec["wdth"] <= spec.get("min_wdth", 75):
            spec["_final_wdth"] = spec["wdth"]
            return cov
        spec["wdth"] = max(spec.get("min_wdth", 75), spec["wdth"] - 5)


def _render_line(text: str, spec: dict, box, cap_ref="H"):
    spec.setdefault("wdth", 100)
    x0, y0, x1, y1 = box
    bw, bh = x1 - x0, y1 - y0
    probe = font(spec, 200)
    cb = probe.getbbox(cap_ref)
    cap = cb[3] - cb[1]
    size = max(4, int(round(200 * bh * SS / cap)))
    f = font(spec, size)
    smallcaps = spec.get("smallcaps", False)
    if smallcaps:
        f2 = font(spec, int(size * spec.get("smallcaps_ratio", 0.78)))
    tb = f.getbbox(cap_ref)
    top_off = tb[1]
    # measure
    parts = [(text[0], f), (text[1:], f2)] if smallcaps else [(text, f)]
    widths = [ff.getlength(t) for t, ff in parts]
    tracking = spec.get("tracking", 0) * SS
    total = sum(widths) + tracking * max(0, len(text) - 1)
    pad_top = int(bh * SS * 0.6)
    H = bh * SS + 2 * pad_top
    W = int(total) + 8 * SS
    canvas = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(canvas)
    x = 4 * SS
    baseline_y = pad_top - top_off  # glyph top of caps at pad_top
    for (t, ff), w in zip(parts, widths):
        if tracking:
            for ch in t:
                d.text((x, baseline_y + (tb[3] - ff.getbbox(cap_ref)[3] if ff is not f else 0)), ch, font=ff, fill=255)
                x += ff.getlength(ch) + tracking
        else:
            dy = (f.getbbox(cap_ref)[3] - ff.getbbox(cap_ref)[3]) if ff is not f else 0
            d.text((x, baseline_y + dy), t, font=ff, fill=255)
            x += w
    arr = np.array(canvas)
    cols = np.nonzero(arr.max(0) > 0)[0]
    arr = arr[:, cols.min():cols.max() + 1]
    ink_w = arr.shape[1]
    target_w = min(ink_w, bw * SS * spec.get("max_width", 1.0)) if not spec.get("stretch") else bw * SS
    sx = target_w / ink_w
    img = Image.fromarray(arr).resize((max(1, int(round(ink_w * sx / SS))), H // SS), Image.LANCZOS)
    cov = np.asarray(img, dtype=np.float64) / 255.0
    # place: cap top at y0; accents may rise above (pad_top/SS rows)
    full = np.zeros((1024, 2048))
    ph = pad_top // SS
    w = cov.shape[1]
    align = spec.get("align", "center")
    if align == "left":
        px = x0
    elif align == "right":
        px = x1 - w
    else:
        px = x0 + (bw - w) // 2
    py = y0 - ph
    ys0, xs0 = max(py, 0), max(px, 0)
    ys1, xs1 = min(py + cov.shape[0], 1024), min(px + w, 2048)
    full[ys0:ys1, xs0:xs1] = cov[ys0 - py:ys1 - py, xs0 - px:xs1 - px]
    return full, ink_w / SS


def connected(m: np.ndarray, sy: int, sx: int) -> np.ndarray:
    """4-connected component of m containing (sy, sx)."""
    from collections import deque
    out = np.zeros_like(m)
    if not m[sy, sx]:
        raise SystemExit("seed not on mask")
    q = deque([(sy, sx)])
    out[sy, sx] = True
    H, W = m.shape
    while q:
        y, x = q.popleft()
        for ny, nx in ((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)):
            if 0 <= ny < H and 0 <= nx < W and m[ny, nx] and not out[ny, nx]:
                out[ny, nx] = True
                q.append((ny, nx))
    return out


def auto_line_box(old_mask, box, safe):
    """Cap box of the ORIGINAL line: top = first inked row, baseline = last row with >= 30% of the peak ink."""
    rows = old_mask.sum(1)
    ink = np.nonzero(rows >= 2)[0]
    heavy = np.nonzero(rows >= 0.3 * rows.max())[0]
    top, base = box[1] + ink.min(), box[1] + heavy.max() + 1
    return [safe[0], top, safe[2], base]


