# ---------------------------------------------------------------- UV evidence
def uv_footprints():
    """Instanced West Coast meshes -> (instances, UV footprint mask on the atlas)."""
    import dae_uv
    usage = json.loads(MESH_USAGE.read_text(encoding="utf8"))
    out = {}
    for dae in sorted(MESH_DIR.rglob("*")):
        if dae.suffix.lower() != ".dae":
            continue
        inst = usage.get(dae.stem, {}).get("instances", 0)
        if inst == 0:
            continue
        mask, items = dae_uv.footprint([dae], "roadsigns", (2048, 1024))
        if items:
            out[dae.stem] = (inst, mask)
    return out


def evidence(box, foot):
    """Meshes whose UV footprint covers >= 40 % of the element box (the element is sampled by them)."""
    x0, y0, x1, y1 = box
    meshes, cover = {}, {}
    for mesh, (inst, mask) in foot.items():
        c = float(mask[y0:y1, x0:x1].mean())
        if c >= 0.4:  # a triangular sign (R-2) fills ~half of its bounding box
            meshes[mesh] = inst
            cover[mesh] = round(c, 3)
    return {"meshes": meshes, "uv_coverage": cover}


def cmd_regions(layout):
    foot = uv_footprints()
    out = {"_doc": "Generated by build_t_roadsigns.py regions: every edited element with the UV quads "
                   "(instanced West Coast meshes, material roadsigns) that sample it.", "elements": []}
    regions_color, regions_opacity = [], []
    for el in layout["elements"]:
        ev = evidence(el["box"], foot)
        if not ev["meshes"] and not el.get("uv_override"):
            raise SystemExit(f"{el['id']}: no instanced UV quad covers {el['box']} -> not an allowed region")
        rec = {"id": el["id"], "op": el["op"], "box": el["box"], **ev}
        out["elements"].append(rec)
        x0, y0, x1, y1 = el["box"]
        src = "UV quads of " + ", ".join(f"{m}.dae ({n} inst.)" for m, n in sorted(ev["meshes"].items())) + "; Phase 5"
        reg = {"id": el["id"], "x": x0, "y": y0, "width": x1 - x0, "height": y1 - y0, "source": src}
        regions_color.append(reg)
        if el["op"] == "glyph":
            regions_opacity.append(reg)
    REGIONS.write_text(json.dumps(out, indent=1) + "\n", encoding="utf8")
    allowed = json.loads(ALLOWED.read_text(encoding="utf8"))
    keep = [r for r in allowed["t_roadsigns_b.color"]["regions"] if r["id"] in
            ()]
    allowed["t_roadsigns_b.color"]["regions"] = keep + regions_color
    allowed["t_roadsigns_o.data"] = {"size": [2048, 1024], "regions": regions_opacity}
    ALLOWED.write_text(json.dumps(allowed, indent=2, ensure_ascii=False) + "\n", encoding="utf8")
    print(f"regions.json: {len(out['elements'])} elements; allowed_regions updated "
          f"({len(regions_color)} colour, {len(regions_opacity)} opacity)")


def cmd_build(layout):
    color, opacity = load_originals()
    rng = np.random.default_rng(20260930)
    done = []
    for el in layout["elements"]:
        OPS[el["op"]](el, color, opacity, rng, done)
    OUT_COLOR.parent.mkdir(parents=True, exist_ok=True)
    Image.fromarray(color, "RGBA").save(OUT_COLOR, optimize=False)
    Image.fromarray(opacity, "RGBA").save(OUT_OPACITY, optimize=False)
    print(f"{len(done)} elements -> {OUT_COLOR.relative_to(REPO)}, {OUT_OPACITY.relative_to(REPO)}")
    geo = {el["id"]: el["_geometry"] for el in layout["elements"] if "_geometry" in el}
    if geo:
        print("geometry:", json.dumps(geo))


def cmd_preview(layout, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    a = Image.open(ORIG_COLOR).convert("RGBA")
    b = Image.open(OUT_COLOR).convert("RGBA")
    ao = Image.open(ORIG_OPACITY).convert("L")
    bo = Image.open(OUT_OPACITY).convert("L")
    tiles = []
    for el in layout["elements"]:
        x0, y0, x1, y1 = el["box"]
        m = 6
        bx = (max(x0 - m, 0), max(y0 - m, 0), min(x1 + m, 2048), min(y1 + m, 1024))
        pa, pb = a.crop(bx), b.crop(bx)
        if el["op"] == "glyph":  # show what the sign shows: colour where mask >= 128
            for im, mo in ((pa, ao), (pb, bo)):
                mm = mo.crop(bx).point(lambda v: 255 if v >= 128 else 0)
                bg = Image.new("RGBA", im.size, (30, 70, 50, 255))
                bg.paste(im, (0, 0), mm)
                im.paste(bg)
        s = 2
        w, h = pa.width * s, pa.height * s
        t = Image.new("RGB", (w * 2 + 6, h + 14), (0, 0, 0))
        t.paste(pa.resize((w, h), Image.LANCZOS).convert("RGB"), (0, 14))
        t.paste(pb.resize((w, h), Image.LANCZOS).convert("RGB"), (w + 6, 14))
        ImageDraw.Draw(t).text((2, 1), el["id"], fill=(255, 255, 0))
        t.save(out_dir / f"{el['id']}.png")
        tiles.append(t)
    print(f"{len(tiles)} previews -> {out_dir}")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["regions", "build", "preview"])
    ap.add_argument("--only", nargs="*", help="restrict to element ids (build/preview)")
    ap.add_argument("--out", default=str(REPO / "working/temporary/t_roadsigns_preview"))
    a = ap.parse_args(argv)
    layout = json.loads(LAYOUT.read_text(encoding="utf8"))
    if a.only:
        layout["elements"] = [e for e in layout["elements"] if e["id"] in a.only]
    if a.cmd == "regions":
        cmd_regions(layout)
    elif a.cmd == "build":
        cmd_build(layout)
    else:
        cmd_preview(layout, Path(a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
