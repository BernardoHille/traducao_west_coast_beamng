"""Deterministic PT-BR composition of the `t_roadsigns` atlas (Phase 5 master).

Starts from the ORIGINAL game PNGs (source/originals/png, SHA-256 checked against the
manifest), edits only the elements listed in layout.json, and writes:

    working/png/t_roadsigns_b.color.png   (base colour)
    working/png/t_roadsigns_o.data.png    (opacity: only glyph tiles change)

    python working/layered/t_roadsigns/build_t_roadsigns.py regions   # UV evidence -> regions.json + allowed_regions.json
    python working/layered/t_roadsigns/build_t_roadsigns.py build     # compose the PNGs
    python working/layered/t_roadsigns/build_t_roadsigns.py preview   # crops before/after in working/temporary

Nothing is generated by AI; everything is text rendered with a system font over the
original pixels, and every pixel outside the element boxes is copied untouched.
"""
